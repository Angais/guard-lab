import fs from 'node:fs/promises';
import path from 'node:path';
import { ROOT } from './paths.mjs';
import { TOOLS, toolSchemas } from '../src/sim/tools.mjs';
import { ITEMS } from '../src/sim/items.mjs';
import { allHumanToolSchemas } from '../src/sim/human-agent.mjs';

const human = new Map(allHumanToolSchemas().map((t) => [t.function.name, t]));
const catalog = {
  format: 1,
  note: 'Complete catalog; current turn schemas further restrict actions. Generated from source.',
  robot: toolSchemas(),
  recoverableRobot: toolSchemas(undefined, { rulesProfile: 'recoverable' }),
  human: [...human.values()].sort((a, b) => a.function.name.localeCompare(b.function.name)),
  items: ITEMS,
};
const clean = (text) => String(text).replaceAll('|', '\\|');
const params = (schema) =>
  Object.entries(schema.function.parameters.properties)
    .map(([name, s]) => `\`${name}\`: ${s.type}${s.enum ? ' (' + s.enum.join(', ') + ')' : ''}`)
    .join('; ') || 'none';
let markdown =
  '# Tool reference\n\nGenerated by `npm run docs:generate`. Do not edit by hand. Current turn schemas are authoritative; ranges, ammunition, vision and cooldowns are enforced by the engine. See [mechanics](MECHANICS.md) for consequences.\n\n## Guard\n\n| Command | Arguments | Range | Uses | Cooldown | Behavior |\n| --- | --- | --- | --- | --- | --- |\n';
for (const t of TOOLS)
  markdown += `| \`${t.name}\` | ${clean(params(catalog.robot.find((s) => s.function.name === t.name)))} | ${t.range} m | ${t.ammo ?? 'unlimited'} | ${t.cooldown ?? 0} | ${clean(t.description)} |\n`;
markdown +=
  '\n## Human\n\nThis is the union across roles, items and positions. Not all actions are callable in one turn. Speech is the only stunned action. `choose_item` happens during AI setup.\n\n| Command | Arguments | Behavior |\n| --- | --- | --- |\n';
for (const schema of catalog.human)
  markdown += `| \`${schema.function.name}\` | ${clean(params(schema))} | ${clean(schema.function.description)} |\n`;
markdown +=
  '\n## Machine-readable catalog\n\n[tool-schemas.json](tool-schemas.json) contains the complete function schemas and item metadata for adapters and agents. The live packet always supplies the currently available subset.\n';
for (const [name, contents] of [
  ['TOOLS.md', markdown],
  ['tool-schemas.json', JSON.stringify(catalog, null, 2) + '\n'],
]) {
  const target = path.join(ROOT, 'docs', name);
  if (process.argv.includes('--check')) {
    if ((await fs.readFile(target, 'utf8').catch(() => '')) !== contents)
      throw new Error('Generated reference is stale: ' + name + '. Run npm run docs:generate.');
  } else await fs.writeFile(target, contents);
}
console.log('Tool reference ' + (process.argv.includes('--check') ? 'verified.' : 'generated.'));
